import React, { useState } from 'react';
import { 
  AIDecisionBrief, 
  InfrastructureNode, 
  CascadeSimulationResult 
} from '../../types';
import { 
  Sparkles, 
  Bot, 
  ShieldCheck, 
  AlertTriangle, 
  Copy, 
  Check, 
  Key, 
  RefreshCw, 
  Layers, 
  Share2 
} from 'lucide-react';

interface AIDecisionBriefViewProps {
  decisionBrief: AIDecisionBrief;
  selectedNode: InfrastructureNode;
  simulationResult: CascadeSimulationResult | null;
  onRefreshBrief: () => void;
}

export const AIDecisionBriefView: React.FC<AIDecisionBriefViewProps> = ({
  decisionBrief,
  selectedNode,
  simulationResult,
  onRefreshBrief
}) => {
  const [apiKey, setApiKey] = useState<string>('');
  const [isCallingLiveApi, setIsCallingLiveApi] = useState<boolean>(false);
  const [copied, setCopied] = useState<boolean>(false);
  const [liveExplanation, setLiveExplanation] = useState<string | null>(null);

  const handleCopy = () => {
    const text = `
NEXUSSTORM AI DECISION BRIEF
Target Node: ${decisionBrief.nodeName} (${selectedNode.code})
Risk Level: ${decisionBrief.riskLevel} (${selectedNode.riskIndex}/100)
Primary Driver: ${decisionBrief.primaryDriver}

1. WHY THIS NODE?
${decisionBrief.whyThisNode}

2. WHAT COULD HAPPEN?
${decisionBrief.whatCouldHappen}

3. WHAT IS MOST CRITICAL?
${decisionBrief.whatIsMostCritical}

4. WHAT SHOULD BE DONE?
${decisionBrief.whatShouldBeDone}

Factor Attribution:
- Hazard Contribution: ${decisionBrief.attribution.hazard}%
- Exposure Contribution: ${decisionBrief.attribution.exposure}%
- Vulnerability Contribution: ${decisionBrief.attribution.vulnerability}%
- Network Dependency: ${decisionBrief.attribution.dependency}%

Generated by NEXUSSTORM AI Explanation Engine
    `.trim();

    navigator.clipboard.writeText(text);
    setCopied(true);
    setTimeout(() => setCopied(false), 2000);
  };

  const handleExecuteLiveGemini = async () => {
    if (!apiKey) return;
    setIsCallingLiveApi(true);
    try {
      const promptText = `You are the critical infrastructure explanation layer for NEXUSSTORM. Explain the cascade failure risk of ${decisionBrief.nodeName} (${selectedNode.code}) under severe coastal cyclone conditions. The node has a Prototype Risk Index of ${selectedNode.riskIndex}/100. Hazard contribution is ${decisionBrief.attribution.hazard}%, Exposure is ${decisionBrief.attribution.exposure}%, Vulnerability is ${decisionBrief.attribution.vulnerability}%, and Network Dependency is ${decisionBrief.attribution.dependency}%. Downstream dependencies include: ${decisionBrief.downstreamServices.join(', ')}. Provide a concise 3-paragraph executive operational brief explaining why it is critical, how the cascade propagates, and what emergency intervention is recommended.`;

      const res = await fetch(`https://generativelanguage.googleapis.com/v1beta/models/gemini-1.5-flash:generateContent?key=${apiKey}`, {
        method: 'POST',
        headers: { 'Content-Type': 'application/json' },
        body: JSON.stringify({
          contents: [{ parts: [{ text: promptText }] }]
        })
      });

      const data = await res.json();
      if (data.candidates && data.candidates[0]?.content?.parts[0]?.text) {
        setLiveExplanation(data.candidates[0].content.parts[0].text);
      } else {
        alert('Could not retrieve Gemini response. Check API key validity.');
      }
    } catch (err) {
      alert('Error contacting Gemini API. Reverting to deterministic model.');
    } finally {
      setIsCallingLiveApi(false);
    }
  };

  return (
    <div className="space-y-6">
      {/* Banner */}
      <div className="bg-[#101A2B] border border-[#1E3A5F] rounded-xl p-6 shadow-xl relative overflow-hidden">
        <div className="flex flex-col md:flex-row md:items-center justify-between gap-4">
          <div>
            <div className="flex items-center gap-2 mb-1.5">
              <span className="text-[10px] font-mono px-2 py-0.5 rounded bg-[#38BDF8]/20 border border-[#38BDF8]/40 text-[#38BDF8] font-bold flex items-center gap-1.5">
                <Sparkles className="w-3.5 h-3.5" />
                AI REASONING LAYER
              </span>
              <span className="text-[10px] font-mono text-[#94A3B8]">
                DECISION-SUPPORT SYNTHESIS
              </span>
            </div>
            <h1 className="text-2xl font-extrabold text-[#F8FAFC] tracking-tight">
              AI DECISION BRIEF
            </h1>
            <p className="text-xs text-[#94A3B8] font-mono mt-0.5">
              Gemini converts structured deterministic cascade graphs into human-readable commander briefs
            </p>
          </div>

          <div className="flex items-center gap-2">
            <span className="text-xs font-mono px-2.5 py-1 rounded bg-[#0B1220] border border-[#1E3A5F] text-[#38BDF8]">
              {liveExplanation ? 'GEMINI 1.5 FLASH: LIVE' : 'AI EXPLANATION — DEMO MODE'}
            </span>
            <button
              onClick={handleCopy}
              className="flex items-center gap-1.5 px-3 py-1.5 rounded-lg bg-[#152238] border border-[#1E3A5F] text-xs font-mono text-[#F8FAFC] hover:border-[#38BDF8] transition-colors"
            >
              {copied ? <Check className="w-3.5 h-3.5 text-[#22C55E]" /> : <Copy className="w-3.5 h-3.5 text-[#94A3B8]" />}
              <span>{copied ? 'Copied' : 'Copy Brief'}</span>
            </button>
          </div>
        </div>

        {/* Live Gemini API Key Input (Optional) */}
        <div className="mt-4 pt-3 border-t border-[#1E3A5F] flex flex-wrap items-center justify-between gap-3 text-xs font-mono">
          <div className="flex items-center gap-2 text-[#94A3B8]">
            <Key className="w-3.5 h-3.5 text-[#38BDF8]" />
            <span>OPTIONAL LIVE GEMINI API:</span>
            <input
              type="password"
              placeholder="Paste Gemini API Key (Optional)"
              value={apiKey}
              onChange={e => setApiKey(e.target.value)}
              className="bg-[#0B1220] border border-[#1E3A5F] rounded px-2.5 py-1 text-xs text-[#F8FAFC] focus:outline-none focus:border-[#38BDF8] w-56 font-mono"
            />
            {apiKey && (
              <button
                onClick={handleExecuteLiveGemini}
                disabled={isCallingLiveApi}
                className="px-2.5 py-1 rounded bg-[#2563EB] text-white hover:bg-[#1D4ED8] transition-colors font-bold disabled:opacity-50"
              >
                {isCallingLiveApi ? 'Calling Gemini...' : 'Run Live Gemini'}
              </button>
            )}
          </div>
          <span className="text-[11px] text-[#94A3B8]">
            Default mode uses deterministic research-grade templates with zero API dependency.
          </span>
        </div>
      </div>

      {/* Main 4-Quadrant Operational Decision Brief (Section 35) */}
      <div className="grid grid-cols-1 md:grid-cols-2 gap-5">
        {/* Quadrant 1: WHY THIS NODE? */}
        <div className="bg-[#101A2B] border border-[#1E3A5F] rounded-xl p-5 shadow-xl relative group hover:border-[#38BDF8]/40 transition-colors">
          <div className="flex items-center gap-2 mb-3 pb-2 border-b border-[#1E3A5F]">
            <div className="w-6 h-6 rounded-md bg-[#38BDF8]/20 border border-[#38BDF8]/40 flex items-center justify-center text-[#38BDF8] font-mono text-xs font-bold">
              01
            </div>
            <h3 className="text-sm font-extrabold font-mono text-[#38BDF8] tracking-wider">
              WHY THIS NODE?
            </h3>
          </div>
          <p className="text-xs text-[#F8FAFC] leading-relaxed font-sans">
            {decisionBrief.whyThisNode}
          </p>
          <div className="mt-4 pt-3 border-t border-[#1E3A5F]/60 flex items-center justify-between text-[11px] font-mono text-[#94A3B8]">
            <span>PRIMARY ATTRIBUTION:</span>
            <span className="text-[#38BDF8] font-bold">{decisionBrief.primaryDriver}</span>
          </div>
        </div>

        {/* Quadrant 2: WHAT COULD HAPPEN? */}
        <div className="bg-[#101A2B] border border-[#1E3A5F] rounded-xl p-5 shadow-xl relative group hover:border-[#EF4444]/40 transition-colors">
          <div className="flex items-center gap-2 mb-3 pb-2 border-b border-[#1E3A5F]">
            <div className="w-6 h-6 rounded-md bg-[#EF4444]/20 border border-[#EF4444]/40 flex items-center justify-center text-[#EF4444] font-mono text-xs font-bold">
              02
            </div>
            <h3 className="text-sm font-extrabold font-mono text-[#EF4444] tracking-wider">
              WHAT COULD HAPPEN?
            </h3>
          </div>
          <p className="text-xs text-[#F8FAFC] leading-relaxed font-sans">
            {decisionBrief.whatCouldHappen}
          </p>
          <div className="mt-4 pt-3 border-t border-[#1E3A5F]/60 flex items-center justify-between text-[11px] font-mono text-[#94A3B8]">
            <span>DOWNSTREAM REACH:</span>
            <span className="text-[#EF4444] font-bold">
              {decisionBrief.downstreamServices.length} Critical Services
            </span>
          </div>
        </div>

        {/* Quadrant 3: WHAT IS MOST CRITICAL? */}
        <div className="bg-[#101A2B] border border-[#1E3A5F] rounded-xl p-5 shadow-xl relative group hover:border-[#F59E0B]/40 transition-colors">
          <div className="flex items-center gap-2 mb-3 pb-2 border-b border-[#1E3A5F]">
            <div className="w-6 h-6 rounded-md bg-[#F59E0B]/20 border border-[#F59E0B]/40 flex items-center justify-center text-[#F59E0B] font-mono text-xs font-bold">
              03
            </div>
            <h3 className="text-sm font-extrabold font-mono text-[#F59E0B] tracking-wider">
              WHAT IS MOST CRITICAL?
            </h3>
          </div>
          <p className="text-xs text-[#F8FAFC] leading-relaxed font-sans">
            {decisionBrief.whatIsMostCritical}
          </p>
          <div className="mt-4 pt-3 border-t border-[#1E3A5F]/60 flex items-center justify-between text-[11px] font-mono text-[#94A3B8]">
            <span>VULNERABILITY FACTOR:</span>
            <span className="text-[#F59E0B] font-bold">Low Elevation &bull; Zero Redundancy</span>
          </div>
        </div>

        {/* Quadrant 4: WHAT SHOULD BE DONE? */}
        <div className="bg-[#101A2B] border border-[#1E3A5F] rounded-xl p-5 shadow-xl relative group hover:border-[#22C55E]/40 transition-colors">
          <div className="flex items-center gap-2 mb-3 pb-2 border-b border-[#1E3A5F]">
            <div className="w-6 h-6 rounded-md bg-[#22C55E]/20 border border-[#22C55E]/40 flex items-center justify-center text-[#22C55E] font-mono text-xs font-bold">
              04
            </div>
            <h3 className="text-sm font-extrabold font-mono text-[#22C55E] tracking-wider">
              WHAT SHOULD BE DONE?
            </h3>
          </div>
          <p className="text-xs text-[#F8FAFC] leading-relaxed font-sans">
            {decisionBrief.whatShouldBeDone}
          </p>
          <div className="mt-4 pt-3 border-t border-[#1E3A5F]/60 flex items-center justify-between text-[11px] font-mono text-[#94A3B8]">
            <span>DISPATCH STATUS:</span>
            <span className="text-[#22C55E] font-bold">Pre-Landfall Action Order Ready</span>
          </div>
        </div>
      </div>

      {/* Live Gemini Generation Output Card (if generated) */}
      {liveExplanation && (
        <div className="bg-[#152238] border-2 border-[#38BDF8] rounded-xl p-5 shadow-glow-sky">
          <div className="flex items-center gap-2 mb-2">
            <Sparkles className="w-4 h-4 text-[#38BDF8]" />
            <h3 className="text-sm font-bold font-mono text-[#38BDF8]">
              LIVE GEMINI SYNTHESIS (REAL-TIME MODEL GENERATION)
            </h3>
          </div>
          <div className="text-xs text-[#F8FAFC] leading-relaxed font-sans whitespace-pre-line">
            {liveExplanation}
          </div>
        </div>
      )}

      {/* Explanatory Architecture Strip */}
      <div className="bg-[#0B1220] border border-[#1E3A5F] rounded-xl p-4 font-mono text-xs text-[#94A3B8] flex flex-wrap items-center justify-between gap-3">
        <div className="flex items-center gap-2">
          <Bot className="w-4 h-4 text-[#38BDF8]" />
          <span>REASONING PIPELINE:</span>
          <span className="text-[#F8FAFC]">DATA → HAZARD → GRAPH → CASCADE → GEMINI → DECISION BRIEF</span>
        </div>
        <div className="text-[11px] text-[#38BDF8]">
          DETERMINISTIC GRAPH VERIFICATION COMPLETED
        </div>
      </div>
    </div>
  );
};
